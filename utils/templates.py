def recommend_templates_for_title(title: str) -> list[str]:
    """Return helpful template suggestions based on the user's job title."""
    needle = (title or "").strip().lower()
    if not needle or needle == "other":
        return ["Prime ATS", "Harmonized", "Modern Professional", "Corporate"]
    scored: dict[str, int] = {}
    for keyword, names in TITLE_TEMPLATE_HINTS.items():
        if keyword in needle:
            for rank, name in enumerate(names):
                if name not in TEMPLATES:
                    continue
                scored[name] = max(scored.get(name, 0), 100 - rank)
    if not scored:
        # Soft fallback: prefer ATS + modern defaults.
        return ["Prime ATS", "Clean", "Harmonized", "Corporate"]
    return sorted(scored.keys(), key=lambda n: (-scored[n], n))


def get_template(name: str) -> dict[str, Any]:
    fallback = TEMPLATES.get("Modern Professional") or next(iter(TEMPLATES.values()))
    return deepcopy(TEMPLATES.get(name) or fallback)


def apply_template_to_profile(
    template_name: str,
    *,
    base_profile: dict[str, Any] | None = None,
    use_reference_labels: bool = False,
) -> dict[str, Any]:
    """Merge a CareerForge template onto an optional reference format profile."""
    template = get_template(template_name)
    profile = dict(base_profile or {})

    for key, value in template.items():
        if key in {"section_labels"} and use_reference_labels and profile.get("section_labels"):
            continue
        if key == "section_order" and use_reference_labels and profile.get("section_order"):
            order = [k for k in profile["section_order"] if k != "projects"]
            for required in ("summary", "skills", "experience", "education"):
                if required not in order:
                    order.append(required)
            profile["section_order"] = order
            continue
        profile[key] = deepcopy(value)

    profile["include_projects_under_experience"] = True
    profile["show_standalone_projects"] = False
    order = list(profile.get("section_order") or PROFESSIONAL_SECTION_ORDER)
    profile["section_order"] = [key for key in order if key != "projects"]
    profile["template_name"] = template_name
    return profile


