def _base(**overrides: Any) -> dict[str, Any]:
    profile: dict[str, Any] = {
        "section_order": list(PROFESSIONAL_SECTION_ORDER),
        "section_labels": dict(DEFAULT_LABELS),
        "name_alignment": "center",
        "contact_alignment": "center",
        "contact_separator": "  ·  ",
        "body_font": "Calibri",
        "name_font": "Calibri",
        "name_font_size": 20,
        "name_bold": True,
        "heading_font_size": 11,
        "heading_all_caps": True,
        "heading_bold": True,
        "heading_underline": True,
        "body_font_size": 10.5,
        "job_line_style": "title_emdash_company",
        "margins_inches": {"top": 0.6, "bottom": 0.6, "left": 0.7, "right": 0.7},
        "include_projects_under_experience": True,
        "show_standalone_projects": False,
        "accent_color": "#0E7C86",
        "name_color": "#0A2F45",
        "title_color": "#0E7C86",
        "text_color": "#102A3A",
        "muted_color": "#5A7585",
        "heading_color": "#0A2F45",
        "rule_color": "#0E7C86",
        "rule_thickness": 1.2,
        "header_rule": True,
        "company_first": False,
        "example_tagline": "Professional ATS resume example",
        "layout_id": "classic",
        "structure_hint": "Single-column professional layout",
        "pdf_header_style": "standard",  # standard | banner | stacked | accent_bar
        "pdf_heading_style": "underline",  # underline | band | plain | double
        "skills_display": "rows",  # rows | compact | chips
        "best_for": [],
    }
    profile.update(overrides)
    if "layout_id" not in overrides and "template_id" in overrides:
        profile["layout_id"] = overrides["template_id"]
    return profile


